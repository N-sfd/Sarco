  widthInches?: number;
  features?: string[];
  /** Short bullets shown on product cards (capacity, cutout, etc.). */
  quickSpecs?: string[];
  /** Washer/dryer load configuration. */
  loadType?: LoadType;
  /** Capacity in cubic feet for laundry / refrigeration filters. */
  capacityCuFt?: number;
