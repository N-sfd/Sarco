function p(
  partial: Omit<Product, "sku" | "financingMonthly"> & { financingMonthly?: number },
): Product {
  return {
    sku: `NX-${partial.model.replace(/[^A-Z0-9]/gi, "").slice(0, 10).toUpperCase()}`,
    financingMonthly:
      partial.financingMonthly ??
      Math.max(19, Math.round((partial.salePrice ?? partial.price) / 24)),
    ...partial,
  };
}

