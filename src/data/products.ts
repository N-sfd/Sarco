export function availabilityLabel(
  availability: Availability,
  storeName?: string | null,
): string {
  switch (availability) {
    case "in_stock":
      return storeName ? `In Stock at ${storeName}` : "In Stock";
    case "limited":
      return "Limited Stock";
    case "delivery":
      return "Available for Delivery";
    case "call":
      return "Call for Availability";
    case "special_order":
      return "Special Order";
  }
}
